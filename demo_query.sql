USE PakistanDriverLicensingDemo;

DECLARE @StartDate DATE = '2026-01-01';
DECLARE @EndDate DATE = '2026-01-31';

SELECT
    S.OFFICE_ID,
    O.OFFICE_NME,
    E.EXAM_ID,
    E.PASS_FAIL_IND,
    E.CDL_FLG,
    E.EXAM_START_TME,
    E.EXAM_END_TME,
    DATEDIFF(SECOND, E.EXAM_START_TME, E.EXAM_END_TME) AS EXAM_DURATION_SECONDS,
    E.EXAM_QUES_NBR,
    E.CORR_QUES_CNT,
    E.INCORR_ANS_CNT,
    E.QUES_ANSW_CNT,
    E.SCORE,
    T.TEST_NAME,
    L.LANG_NME AS LANGUAGE,
    CASE WHEN E.PASS_FAIL_IND = 'P' THEN 1 ELSE 0 END AS PASS_COUNT,
    CASE WHEN E.PASS_FAIL_IND = 'F' THEN 1 ELSE 0 END AS FAIL_COUNT,
    CASE WHEN E.CDL_FLG = 'Y' THEN 1 ELSE 0 END AS CDL_COUNT,
    CASE
        WHEN EXISTS (
            SELECT 1
            FROM PUBLIC_AKTE.AUDIT_HISTORY A
            WHERE A.RETRIEVAL_KEY_TOKEN = S.WORKSTATION_IP_TOKEN
              AND A.TABLE_NME = 'FINGERPRINT'
              AND A.FIELD_NME = 'ERROR'
              AND A.NEW_VALUE LIKE 'Reached max of 3%'
              AND A.LSTMODUSR_TME <= S.SESSION_START_TME
              AND A.LSTMODUSR_TME >= DATEADD(SECOND, -900, S.SESSION_START_TME)
        ) THEN 1
        ELSE 0
    END AS SECONDARY_VERIF_FLAG,
    D.DL_CLASS_CD,
    D.MAIL_CITY,
    D.MAIL_ADDR_EFF_DT
FROM PUBLIC_AKTE.FACT_EXAMS E
JOIN PUBLIC_AKTE.FACT_SESSIONS S
    ON S.SESSION_ID = E.SESSION_ID
   AND S.OFFICE_ID = E.OFFICE_ID
JOIN PUBLIC_AKTE.DIM_OFFICE O
    ON O.OFFICE_ID = S.OFFICE_ID
JOIN PUBLIC_AKTE.REF_TESTS T
    ON T.TEST_ID = E.TEST_ID
JOIN PUBLIC_AKTE.REF_LANG L
    ON L.LANG_ID = E.LANG_ID
JOIN PUBLIC_AKTE.DIM_VAULT V
    ON V.VAULT_ID = S.VAULT_ID
LEFT JOIN PUBLIC_DL.V_DL_MASTER_NONCONF D
    ON D.DLID_TOKEN = V.DL_TOKEN
WHERE S.SESSION_START_TME >= @StartDate
  AND S.SESSION_START_TME < DATEADD(DAY, 1, @EndDate)
  AND E.EXAM_START_TME >= @StartDate
  AND E.EXAM_START_TME < DATEADD(DAY, 1, @EndDate)
  AND E.PASS_FAIL_IND IN ('P', 'F')
  AND (
      E.CMPLTN_RSN_CD IS NULL
      OR E.CMPLTN_RSN_CD NOT IN ('B', 'F')
  )
  AND T.TEST_NAME NOT IN (
      'Ambulance Test',
      'Dealer Test',
      'Driving School Instructor Test',
      'Driving School Operator Test',
      'Firefighter Endorsement Test',
      'Traffic Violator School Instructor Test',
      'Traffic Violator School Operator Test'
  )
ORDER BY E.EXAM_START_TME;
