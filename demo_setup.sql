END;

IF OBJECT_ID(N'PUBLIC_AKTE.DIM_VAULT', N'U') IS NULL
BEGIN
    CREATE TABLE PUBLIC_AKTE.DIM_VAULT (
        VAULT_ID VARCHAR(40) NOT NULL PRIMARY KEY,
        DL_TOKEN VARCHAR(120) NOT NULL UNIQUE
    );
END;

IF OBJECT_ID(N'PUBLIC_AKTE.FACT_SESSIONS', N'U') IS NULL
BEGIN
    CREATE TABLE PUBLIC_AKTE.FACT_SESSIONS (
        SESSION_ID VARCHAR(40) NOT NULL,
        OFFICE_ID INT NOT NULL,
        VAULT_ID VARCHAR(40) NOT NULL,
        WORKSTATION_IP_TOKEN VARCHAR(120) NOT NULL,
        SESSION_START_TME DATETIME2(0) NOT NULL,
        LSTMODUSR_NME VARCHAR(100) NOT NULL,
        PRIMARY KEY (SESSION_ID, OFFICE_ID),
        FOREIGN KEY (OFFICE_ID) REFERENCES PUBLIC_AKTE.DIM_OFFICE (OFFICE_ID),
        FOREIGN KEY (VAULT_ID) REFERENCES PUBLIC_AKTE.DIM_VAULT (VAULT_ID)
    );
END;

IF OBJECT_ID(N'PUBLIC_AKTE.FACT_EXAMS', N'U') IS NULL
BEGIN
    CREATE TABLE PUBLIC_AKTE.FACT_EXAMS (
        EXAM_ID VARCHAR(40) NOT NULL PRIMARY KEY,
        SESSION_ID VARCHAR(40) NOT NULL,
        OFFICE_ID INT NOT NULL,
        TEST_ID INT NOT NULL,
        LANG_ID INT NOT NULL,
        CDL_FLG CHAR(1) NOT NULL CHECK (CDL_FLG IN ('Y', 'N')),
        PASS_FAIL_IND CHAR(1) NOT NULL CHECK (PASS_FAIL_IND IN ('P', 'F')),
        EXAM_START_TME DATETIME2(0) NOT NULL,
        EXAM_END_TME DATETIME2(0) NOT NULL,
        EXAM_QUES_NBR INT NOT NULL,
        MAX_INCORR_NBR INT NOT NULL,
        INCORR_ANS_CNT INT NOT NULL,
        CORR_QUES_CNT INT NOT NULL,
        QUES_ANSW_CNT INT NOT NULL,
        SCORE DECIMAL(5, 2) NOT NULL,
        CMPLTN_RSN_CD VARCHAR(10) NULL,
        FOREIGN KEY (SESSION_ID, OFFICE_ID)
            REFERENCES PUBLIC_AKTE.FACT_SESSIONS (SESSION_ID, OFFICE_ID),
        FOREIGN KEY (TEST_ID) REFERENCES PUBLIC_AKTE.REF_TESTS (TEST_ID),
        FOREIGN KEY (LANG_ID) REFERENCES PUBLIC_AKTE.REF_LANG (LANG_ID),
        CHECK (EXAM_START_TME < EXAM_END_TME),
        CHECK (EXAM_QUES_NBR >= 0 AND MAX_INCORR_NBR >= 0),
        CHECK (INCORR_ANS_CNT >= 0 AND CORR_QUES_CNT >= 0),
        CHECK (QUES_ANSW_CNT >= 0 AND QUES_ANSW_CNT <= EXAM_QUES_NBR),
        CHECK (CORR_QUES_CNT + INCORR_ANS_CNT = QUES_ANSW_CNT),
        CHECK (SCORE >= 0 AND SCORE <= 100)
    );
END;

IF OBJECT_ID(N'PUBLIC_AKTE.AUDIT_HISTORY', N'U') IS NULL
BEGIN
    CREATE TABLE PUBLIC_AKTE.AUDIT_HISTORY (
