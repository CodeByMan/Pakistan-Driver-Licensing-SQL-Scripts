END;

IF OBJECT_ID(N'PUBLIC_AKTE.REF_TESTS', N'U') IS NULL
BEGIN
    CREATE TABLE PUBLIC_AKTE.REF_TESTS (
        TEST_ID INT NOT NULL PRIMARY KEY,
        TEST_NAME VARCHAR(120) NOT NULL UNIQUE
    );
END;

IF OBJECT_ID(N'PUBLIC_AKTE.REF_LANG', N'U') IS NULL
BEGIN
    CREATE TABLE PUBLIC_AKTE.REF_LANG (
