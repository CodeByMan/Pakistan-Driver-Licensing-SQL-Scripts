USE PakistanDriverLicensingDemo;

SELECT 'DIM_OFFICE' AS TABLE_NAME, COUNT(*) AS ROW_COUNT
FROM PUBLIC_AKTE.DIM_OFFICE
UNION ALL
SELECT 'REF_TESTS', COUNT(*) FROM PUBLIC_AKTE.REF_TESTS
UNION ALL
SELECT 'REF_LANG', COUNT(*) FROM PUBLIC_AKTE.REF_LANG
UNION ALL
SELECT 'DIM_VAULT', COUNT(*) FROM PUBLIC_AKTE.DIM_VAULT
UNION ALL
SELECT 'FACT_SESSIONS', COUNT(*) FROM PUBLIC_AKTE.FACT_SESSIONS
UNION ALL
SELECT 'FACT_EXAMS', COUNT(*) FROM PUBLIC_AKTE.FACT_EXAMS
UNION ALL
SELECT 'AUDIT_HISTORY', COUNT(*) FROM PUBLIC_AKTE.AUDIT_HISTORY
UNION ALL
SELECT 'V_DL_MASTER_NONCONF', COUNT(*) FROM PUBLIC_DL.V_DL_MASTER_NONCONF;

SELECT COUNT(*) AS INVALID_EXAM_COUNT
FROM PUBLIC_AKTE.FACT_EXAMS
WHERE EXAM_START_TME >= EXAM_END_TME
   OR PASS_FAIL_IND NOT IN ('P', 'F')
   OR CDL_FLG NOT IN ('Y', 'N')
   OR SCORE < 0 OR SCORE > 100
   OR EXAM_QUES_NBR < 0
   OR MAX_INCORR_NBR < 0
   OR INCORR_ANS_CNT < 0
   OR CORR_QUES_CNT < 0
   OR QUES_ANSW_CNT < 0
   OR QUES_ANSW_CNT > EXAM_QUES_NBR
   OR CORR_QUES_CNT + INCORR_ANS_CNT <> QUES_ANSW_CNT;

SELECT COUNT(*) AS MISSING_EXAM_REFERENCE_COUNT
FROM PUBLIC_AKTE.FACT_EXAMS E
LEFT JOIN PUBLIC_AKTE.FACT_SESSIONS S
    ON S.SESSION_ID = E.SESSION_ID
   AND S.OFFICE_ID = E.OFFICE_ID
LEFT JOIN PUBLIC_AKTE.REF_TESTS T
    ON T.TEST_ID = E.TEST_ID
LEFT JOIN PUBLIC_AKTE.REF_LANG L
    ON L.LANG_ID = E.LANG_ID
WHERE S.SESSION_ID IS NULL
   OR T.TEST_ID IS NULL
   OR L.LANG_ID IS NULL;

SELECT COUNT(*) AS MISSING_SESSION_REFERENCE_COUNT
FROM PUBLIC_AKTE.FACT_SESSIONS S
LEFT JOIN PUBLIC_AKTE.DIM_OFFICE O
    ON O.OFFICE_ID = S.OFFICE_ID
LEFT JOIN PUBLIC_AKTE.DIM_VAULT V
    ON V.VAULT_ID = S.VAULT_ID
WHERE O.OFFICE_ID IS NULL
   OR V.VAULT_ID IS NULL;
